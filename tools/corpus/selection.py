def parse(token):
    """'9.30-31' -> (9, 30, 31); '2.47' -> (2, 47, 47)."""
    ch, rest = token.split(".")
    if "-" in rest:
        a, b = rest.split("-")
    else:
        a = b = rest
    return int(ch), int(a), int(b)


def passages():
    """Список (тема, глава, с, по) в порядке состояний и порядке внутри состояния."""
    out = []
    taken = set()
    for theme, line in THEMES.items():
        for token in line.split():
            ch, a, b = parse(token)
            assert b >= a, token
            for v in range(a, b + 1):
                assert (ch, v) not in taken, f"стих {ch}.{v} встречается дважды ({token})"
                taken.add((ch, v))
            out.append((theme, ch, a, b))
    return out


if __name__ == "__main__":
    p = passages()
    print(len(p), "отрывков,", len({t for t, *_ in p}), "состояний")
    for theme in THEMES:
        print(theme, sum(1 for t, *_ in p if t == theme))
