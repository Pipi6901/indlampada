import DeepamCore
import SwiftUI

/// Названия языков и изданий.
///
/// Живут отдельным файлом, а не в онбординге, где были раньше: их читают и
/// «Вид», и лист выбора языка, и подпись под стихом. Привязка к экрану, который
/// человек видит один раз в жизни, была случайной.
///
/// Названия НЕ переводятся: язык в списке подписан на себе самом, иначе
/// человек, открывший приложение на чужом языке, не найдёт свой. Издания — имена
/// собственные, у них перевода нет вовсе.
extension AppLocale {
    var nativeName: String {
        switch self {
        case .en: "English"
        }
    }

    /// Короткое имя издания для подписи под стихом: длинное не влезает.
    var editionShort: String {
        switch self {
        case .en: "Besant"
        }
    }

    var editionName: String {
        switch self {
        case .en: "Annie Besant, 1922"
        }
    }

    /// Строка авторства под изданием в листе выбора языка. Санскрит и перевод — из одной
    /// книги, срок защиты которой истёк (переводчица умерла в 1933 году), так что указать
    /// достаточно имя и год; полное уведомление лежит ниже, на самом листе.
    var editionCredit: String? {
        switch self {
        case .en: "Sanskrit text and translation: public domain"
        }
    }
}
